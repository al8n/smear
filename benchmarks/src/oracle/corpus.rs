/// Where a document came from, for the report's per-family breakdown.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Provenance {
  /// One half of a per-rule liveness fixture.
  SpecFixture,
  /// A draft §5 example or counter-example beyond the fixture table.
  SpecExample,
  /// Written to exercise one of the four whitelist classes.
  WhitelistProbe,
  /// An unmutated realistic document.
  Realistic,
  /// Generated by [`super::mutate`] from a realistic seed.
  Mutant,
  /// Ingested from an `apollo-rs` checkout.
  ApolloTestData,
}

impl fmt::Display for Provenance {
  fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
    f.write_str(match self {
      Self::SpecFixture => "spec-fixture",
      Self::SpecExample => "spec-example",
      Self::WhitelistProbe => "whitelist-probe",
      Self::Realistic => "realistic",
      Self::Mutant => "mutant",
      Self::ApolloTestData => "apollo-test-data",
    })
  }
}

/// One executable document, and what the harness knows about it before running it.
#[derive(Debug, Clone)]
pub struct Case {
  /// Unique within its suite.
  pub name: String,
  /// The executable document.
  pub document: String,
  /// Which family it belongs to.
  pub provenance: Provenance,
  /// The whitelist class that excuses a divergence here, if any.
  ///
  /// `Some` is a *requirement*, not a permission: see
  /// [`Divergence::WhitelistViolated`](super::Divergence::WhitelistViolated).
  pub class: Option<Class>,
  /// A whitelist class this case is *allowed* to land in, without being required to.
  ///
  /// The generated family's door, and the only one it has. A mutant cannot carry [`Case::class`]:
  /// that field asserts a divergence, and a mutant is by construction a document nobody has looked
  /// at, most of which do not diverge at all. But a mutation seed containing a `@oneOf` input can
  /// obviously produce a W4 document — dropping one `!` does it — and refusing to say so would
  /// force the corpus to shed exactly the seeds worth mutating.
  ///
  /// So the permission lives on the **seed**, where a human decided it, and every mutant of that
  /// seed inherits it. Five seeds carry a decision instead of four hundred mutants carrying none.
  ///
  /// Deliberately *not* inferred from what smear fired. "smear fired 5.8.5 and apollo said nothing"
  /// is the shape of W2 and also the shape of a false positive in smear's 5.8.5, and a harness that
  /// cannot tell those apart has stopped being an oracle. The only class where the inference would
  /// be sound is W1 — apollo has no 5.6.3 at all, so any firing of it is unmatched by construction
  /// — and nothing in the corpus needs it, so it is not built.
  pub permits: Option<Class>,
  /// The rule the case was written for, when it was written for one. Message-only.
  pub exercises: Option<Rule>,
}

impl Case {
  /// A case with nothing declared about it: the verdicts must simply match.
  pub fn new(name: impl Into<String>, document: impl Into<String>, provenance: Provenance) -> Self {
    Self {
      name: name.into(),
      document: document.into(),
      provenance,
      class: None,
      permits: None,
      exercises: None,
    }
  }

  /// Declares the whitelist class that must explain this case's divergence.
  #[must_use]
  pub fn class(mut self, class: Class) -> Self {
    self.class = Some(class);
    self
  }

  /// Allows — but does not require — this case to land in a whitelist class.
  #[must_use]
  pub fn permits(mut self, class: Class) -> Self {
    self.permits = Some(class);
    self
  }

  /// Records the rule the case exists for, so a failure message can name it.
  #[must_use]
  pub fn exercises(mut self, rule: Rule) -> Self {
    self.exercises = Some(rule);
    self
  }
}

/// One schema and every document run against it.
///
/// Grouped this way because building is the expensive half on both sides and a server builds once,
/// so the harness's shape matches the shape the design is optimised for.
#[derive(Debug, Clone)]
pub struct Suite {
  /// Used as the first half of every failure's case name.
  pub name: String,
  /// The SDL both sides build.
  pub sdl: String,
  /// The documents.
  pub cases: Vec<Case>,
}

