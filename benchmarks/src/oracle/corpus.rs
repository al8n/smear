/// The fixture pairs' valid halves, used as mutation seeds.
fn fixture_twins() -> Vec<&'static str> {
  let mut twins: Vec<_> = PAIRS.iter().map(|pair| pair.valid).collect();
  twins.sort_unstable();
  twins.dedup();
  twins
}

