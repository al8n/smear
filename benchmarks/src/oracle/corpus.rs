//! The documents the oracle runs, and where each of them came from.
//!
//! # The families, and what each is for
//!
//! * [`Provenance::SpecFixture`] — the per-rule liveness fixtures, both halves of every pair. They
//!   are the specification's own §5 counter-examples, and they are what guarantees the corpus
//!   *reaches* all twenty-eight rules rather than whichever ones a hand-written sample happens to
//!   trip. [`exercised_rules`] proves that mechanically instead of asserting it in prose.
//! * [`Provenance::SpecExample`] — further draft §5 shapes the fixture table does not need,
//!   because the liveness floor only needs one document per rule: unions and `__typename`,
//!   introspection roots, literal coercion at every scalar, list-singleton coercion, directive
//!   placement, subscriptions through spreads.
//! * [`Provenance::WhitelistProbe`] — the documents that exercise the four apollo gaps. Written on
//!   purpose, because a whitelist class nothing hits is an unexamined excuse and the gate refuses
//!   to pass with one.
//! * [`Provenance::Mutant`] and [`Provenance::Realistic`] — the mechanical family. Realistic seeds
//!   (the design spec's own perf baseline, and the federation supergraph the parser benchmarks
//!   already use) broken one token at a time by [`super::mutate`].
//!
//! A fifth, [`Provenance::ApolloTestData`], is opt-in: point `SMEAR_APOLLO_RS_TEST_DATA` at a
//! checkout of `apollo-rs` and [`external`] ingests `apollo-compiler`'s own `test_data` corpus. CI
//! does exactly that, from a tarball pinned to the `apollo-compiler@1.32.0` tag. Not vendored,
//! because a hundred-and-sixty-file copy of another project's fixtures is a licensing and drift
//! liability for evidence a pinned fetch reproduces; see that function's documentation for the
//! split it has to perform to use them at all.
//!
//! # The schema comparison
//!
//! [`SDL_DIRECTIVE_PROBES`] carries suites with **no documents**. Building the schema is itself a
//! comparison — smear's draft §3 pass against apollo's — and those suites exist only for it. It is
//! the comparison that found smear issue #91.

use std::{fmt, fs, path::Path};

use apollo_compiler::ast as apollo_ast;
