  "directive @onObject on OBJECT\ntype Query @onObject { ok: Int }";

/// The mechanical family: realistic seeds and every one-token mutation of them.
pub fn generated() -> Vec<Suite> {
  let mut suites = Vec::new();

  for (name, sdl, seed) in [
    ("realistic", REALISTIC_SDL, REALISTIC_QUERY),
    ("supergraph", SUPERGRAPH, SUPERGRAPH_QUERY),
  ] {
    let mut cases = vec![Case::new("seed", seed, Provenance::Realistic)];
    cases.extend(
      mutate::mutants(seed)
        .into_iter()
        .map(|mutant| Case::new(mutant.name, mutant.source, Provenance::Mutant)),
    );
    suites.push(Suite {
      name: name.to_owned(),
      sdl: sdl.to_owned(),
      cases,
    });
  }

  // The menagerie's own valid documents are the densest source of *schema-aware* mutants: they are
  // small, they cover every rule's neighbourhood, and mutating them lands inside shapes the
  // realistic seeds never reach — enum literals, oneOf inputs, interface conditions.
  let mut cases = Vec::new();
  let seeds: Vec<(&str, Option<Class>)> = fixture_twins()
    .into_iter()
    .map(|twin| (twin, None))
    .chain(MENAGERIE_SEEDS.iter().copied())
    .collect();
  for (index, (seed, permits)) in seeds.iter().enumerate() {
    for mutant in mutate::mutants(seed) {
      let mut case = Case::new(
        format!("seed{index}/{}", mutant.name),
        mutant.source,
        Provenance::Mutant,
      );
      if let Some(class) = permits {
        case = case.permits(*class);
      }
      cases.push(case);
    }
  }
  suites.push(Suite {
    name: "menagerie-mutants".to_owned(),
    sdl: MENAGERIE.to_owned(),
    cases,
  });

  suites
}

/// `apollo-compiler`'s own `test_data`, when `SMEAR_APOLLO_RS_TEST_DATA` points at it.
///
/// # Why it is not vendored
///
/// It is a hundred and sixty documents belonging to another project. Copying them in buys a wider
/// run at the cost of a licensing footnote on every file and a corpus that silently ages against
/// its upstream; leaving them opt-in keeps the committed gate self-contained and reproducible,
/// and the wide run available to anyone with the checkout. The report says how many cases came
/// from here, so a run without it cannot be mistaken for a run with it.
///
/// # Why the files have to be split
///
/// Every file in that corpus is one document mixing type-system and executable definitions —
/// apollo's own harness feeds them whole. smear's validator takes an
/// `ast::ExecutableDocument`, an entry point whose type cannot represent a type-system definition
/// at all (draft 5.1.1 is discharged by construction). So the file is parsed once with apollo's
/// AST parser, partitioned by
/// [`Definition::is_executable_definition`][apollo_ast::Definition::is_executable_definition], and
/// each half printed back to text. Both implementations then read the *same* two texts, so the
/// split is corpus preparation and not an asymmetry: neither side sees anything the other does
/// not.
pub fn external() -> Vec<Suite> {
  let Ok(root) = std::env::var("SMEAR_APOLLO_RS_TEST_DATA") else {
    return Vec::new();
  };
  let mut suites = Vec::new();
  for directory in ["ok", "diagnostics"] {
    let path = Path::new(&root).join(directory);
    let Ok(entries) = fs::read_dir(&path) else {
      continue;
    };
    let mut files: Vec<_> = entries
      .filter_map(Result::ok)
      .map(|entry| entry.path())
      .filter(|path| {
        path
          .extension()
          .is_some_and(|extension| extension == "graphql")
      })
      .collect();
    files.sort();

    for file in files {
      let Ok(text) = fs::read_to_string(&file) else {
        continue;
      };
      // A file the AST parser cannot read is a *parser* fixture — apollo's corpus has those on
      // purpose — and it has no place in a validator differential.
      let Ok(document) = apollo_ast::Document::parse(&text, "corpus.graphql") else {
        continue;
      };

      let mut sdl = String::new();
      let mut executable = String::new();
      for definition in &document.definitions {
        let target = if definition.is_executable_definition() {
          &mut executable
        } else {
          &mut sdl
        };
        target.push_str(&definition.to_string());
        target.push('\n');
      }
      if executable.trim().is_empty() {
        continue;
      }

      let stem = file
        .file_stem()
        .map(|stem| stem.to_string_lossy().into_owned())
        .unwrap_or_else(|| "unnamed".to_owned());
      suites.push(Suite {
        name: format!("apollo-rs/{directory}/{stem}"),
        sdl,
        cases: vec![Case::new(
          "document",
          executable,
          Provenance::ApolloTestData,
        )],
      });
    }
  }
  suites
}

