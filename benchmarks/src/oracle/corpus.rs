/// Every rule the curated corpus is written to exercise.
///
/// The anti-drift mechanism. The fixture pairs above are transcribed from
/// `smear/tests/validator_rules.rs`, and a transcription can rot; what stops it rotting into a
/// corpus that quietly stops reaching half the rule set is that the gate compares this against
/// `Rule::ALL` and fails on any rule with no case. That is a stronger property than "the two files
/// are in sync", and it is the property the oracle actually needs.
pub fn exercised_rules() -> Vec<Rule> {
  let mut rules: Vec<_> = curated()
    .iter()
    .flat_map(|suite| suite.cases.iter())
    .filter_map(|case| case.exercises)
    .collect();
  rules.sort_unstable();
  rules.dedup();
  rules
}
