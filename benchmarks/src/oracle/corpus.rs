/// The specification's own §5 menagerie, extended with the shapes the later rules need.
///
/// Byte-identical in intent to the schema `smear/tests/validator_rules.rs` uses, with one
/// addition: `directive @oneOf on INPUT_OBJECT` is spelled out. smear injects it as a built-in and
/// a document that spells a built-in out replaces it with the same definition, so smear's side is
/// unchanged — but `apollo-compiler` 1.32 has never heard of `@oneOf` (the string does not occur
/// anywhere in its source), and without the declaration it rejects the whole SDL as using an
/// undefined directive. Declaring it is what lets the W4 probes run at all: apollo then sees an
/// ordinary user directive with no semantics attached, which is precisely the gap W4 records.
pub const MENAGERIE: &str = r#"
directive @oneOf on INPUT_OBJECT

type Query {
  dog: Dog
  human: Human
  pet: Pet
  catOrDog: CatOrDog
  empty: Empty
  arguments: Arguments
  findDog(searchBy: FindDogInput): Dog
  booleanList(booleanListArg: [Boolean!]): Boolean
  requiredInput(input: RequiredInput!): Boolean
  nest: Nest
  recursive(input: Recursive): Boolean
}

type Nest {
  nest: Nest
  leaf: Int
}

input Recursive {
  rec: Recursive
  n: Int
}

type Mutation {
  addPet(pet: PetInput!): Pet
  addPets(pets: [PetInput!]!): [Pet]
}

type Subscription {
  newMessage: Message
  disallowedSecondRootField: Boolean
}

type Message {
  body: String
  sender: String
}

interface Sentient {
  name: String!
}

interface Pet {
  name: String!
}

interface Empty {
  nothing: Int
}

type Alien implements Sentient {
  name: String!
  homePlanet: String
}

type Human implements Sentient {
  name: String!
  pets: [Pet]
}

enum DogCommand {
  SIT
  DOWN
  HEEL
}

type Dog implements Pet {
  name: String!
  nickname: String
  barkVolume: Int
  doesKnowCommand(dogCommand: DogCommand!): Boolean!
  isHouseTrained(atOtherHomes: Boolean): Boolean!
  owner: Human
}

enum CatCommand {
  JUMP
}

type Cat implements Pet {
  name: String!
  nickname: String
  doesKnowCommand(catCommand: CatCommand!): Boolean!
  meowVolume: Int
}

union CatOrDog = Cat | Dog
union HumanOrAlien = Human | Alien

scalar CustomScalar

type Arguments {
  multipleRequirements(x: Int!, y: Int!): Int!
  booleanArgField(booleanArg: Boolean): Boolean
  floatArgField(floatArg: Float): Float
  intArgField(intArg: Int): Int
  idArgField(idArg: ID): ID
  stringArgField(stringArg: String): String
  enumArgField(enumArg: DogCommand): Boolean
  customScalarArgField(customArg: CustomScalar): Boolean
  nonNullBooleanArgField(nonNullBooleanArg: Boolean!): Boolean!
  booleanListArgField(booleanListArg: [Boolean]!): [Boolean]
  optionalNonNullBooleanArgField(optionalBooleanArg: Boolean! = false): Boolean!
}

input FindDogInput {
  name: String
  owner: String
}

input RequiredInput {
  req: Int!
  opt: Int
}

input CatInput {
  name: String!
}

input DogInput {
  name: String!
}

input PetInput @oneOf {
  cat: CatInput
  dog: DogInput
}

directive @onQuery on QUERY
directive @repeatableField repeatable on FIELD
"#;

